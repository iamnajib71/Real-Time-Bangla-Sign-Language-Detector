"""Create clearly synthetic fixtures for pipeline correctness tests."""
from pathlib import Path
import cv2
import numpy as np

root=Path('tests/fixtures'); root.mkdir(parents=True,exist_ok=True)
dark=np.zeros((48,64,3),np.uint8); dark[:,:8]=255
bright=255-dark
cv2.imwrite(str(root/'dark.png'),dark); cv2.imwrite(str(root/'bright.png'),bright)
writer=cv2.VideoWriter(str(root/'bimodal.avi'),cv2.VideoWriter_fourcc(*'MJPG'),4,(64,48))
if not writer.isOpened():
    raise RuntimeError('MJPG writer unavailable')
for frame in [dark]*4+[bright]*4:
    writer.write(frame)
writer.release()
(root/'README.md').write_text('Synthetic black/white test patterns and an eight-frame MJPG video generated by scripts/make_fixtures.py. These are software fixtures, not sign-language data or accuracy evidence.\n')
